async function seed() {
  await mongoose.connect(process.env.MONGO_URI);

  const owner = await User.findOne();
  if (!owner) {
    console.error('אין אף משתמש ב-DB - קודם צריך להירשם דרך האפליקציה כדי שיהיה למי לשייך את המתכונים.');
    process.exit(1);
  }

  const docs = recipes.map((r) => ({ ...r, owner: owner._id }));

  // אם המתכון כבר קיים (לפי שם) - רק מעדכנים את התמונה שלו; אחרת יוצרים אותו מחדש
  const existing = await Recipe.find({ title: { $in: recipes.map((r) => r.title) } }).select('title');
  const existingTitles = new Set(existing.map((r) => r.title));

  const toInsert = docs.filter((r) => !existingTitles.has(r.title));
  const toUpdate = docs.filter((r) => existingTitles.has(r.title));

  if (toInsert.length > 0) {
    const inserted = await Recipe.insertMany(toInsert);
    console.log(`נוספו ${inserted.length} מתכונים חדשים:`);
    inserted.forEach((r) => console.log(' -', r.title));
  }

  if (toUpdate.length > 0) {
    for (const r of toUpdate) {
      await Recipe.updateOne({ title: r.title }, { $set: { imageUrl: r.imageUrl } });
    }
    console.log(`עודכנה תמונה עבור ${toUpdate.length} מתכונים קיימים.`);
  }

  if (toInsert.length === 0 && toUpdate.length === 0) {
    console.log('שום דבר לעדכן.');
  }

  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
